import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { defineConfig, loadEnv, type Plugin } from 'vite'

const envDir = fileURLToPath(new URL('../..', import.meta.url))

// Fills %CSP_CONNECT_SRC% in index.html: the API, and the game server over BOTH ws(s) and
// http(s) — Colyseus matchmakes over HTTP before upgrading to a WebSocket (docs/security.md).
const cspConnectSrc = (mode: string): Plugin => {
  const env = loadEnv(mode, envDir, 'VITE_')
  const api = env.VITE_API_URL ?? ''
  const ws = env.VITE_GAME_SERVER_URL ?? ''
  const http = ws.replace(/^ws(s?):/, 'http$1:')
  const sources = [...new Set([api, ws, http].filter(Boolean))].join(' ')
  // Same-site API: the static host proxies /api/* to the real API so the refresh cookie is
  // first-party on every browser (Safari blocks third-party cookies). docs/deploy.md §0c.
  const proxyTarget = (env.VITE_API_PROXY_TARGET ?? '').replace(/\/+$/, '')
  const redirects = [
    '# Generated by vite.config.ts (headers/redirects templates).',
    ...(proxyTarget ? [`/api/*  ${proxyTarget}/:splat  200`] : []),
    '# Single-page app: every other path serves index.html (react-router handles it).',
    '/*  /index.html  200',
    '',
  ].join('\n')
  return {
    name: 'jhandi-csp-connect-src',
    transformIndexHtml: (html) => html.replaceAll('%CSP_CONNECT_SRC%', sources),
    // Netlify/Cloudflare `_headers` must carry the same connect-src, so it is generated too.
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: '_redirects', source: redirects })
      this.emitFile({
        type: 'asset',
        fileName: '_headers',
        source: readFileSync(new URL('./headers.template', import.meta.url), 'utf8').replaceAll(
          '%CSP_CONNECT_SRC%',
          sources,
        ),
      })
    },
  }
}

export default defineConfig(({ mode }) => ({
  // Sub-path hosting, e.g. VITE_BASE_PATH=/game/ for https://example.com/game/ (docs/deploy.md).
  base: loadEnv(mode, envDir, 'VITE_').VITE_BASE_PATH || '/',
  plugins: [react(), tailwindcss(), cspConnectSrc(mode)],
  envDir,
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  server: { port: 5173, strictPort: true },
}))
